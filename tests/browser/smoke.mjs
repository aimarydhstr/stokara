import { chromium, expect } from '@playwright/test';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
const base = process.env.STOKARA_TEST_URL || 'http://127.0.0.1:8000';
const envText = await readFile('.env', 'utf8');
const env = Object.fromEntries(envText.split(/\r?\n/).filter(line => /^[A-Z_]+=/.test(line)).map(line => { const at = line.indexOf('='); return [line.slice(0, at), line.slice(at + 1).replace(/^"|"$/g, '')]; }));
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'id-ID' });
const page = await context.newPage();
const issues = [];
page.on('pageerror', error => issues.push(error.message));
page.on('response', response => { if (response.status() >= 500) issues.push(`${response.status()} ${new URL(response.url()).pathname}`); });
const results = [];
const check = (name, passed = true) => { results.push({ name, passed }); if (!passed) throw new Error(name); };
await mkdir('docs/screenshots', { recursive: true });
try {
  let response = await page.goto(`${base}/login`);
  check('Login page returns HTTP 200', response.status() === 200);
  await expect(page.getByRole('heading', { name: 'Selamat datang kembali.' })).toBeVisible();
  await page.screenshot({ path: 'docs/screenshots/login-desktop.png', fullPage: true });
  await page.getByLabel('Alamat email').fill(env.STOKARA_ADMIN_EMAIL);
  await page.getByLabel('Kata sandi', { exact: true }).fill(env.STOKARA_ADMIN_PASSWORD);
  await page.getByRole('button', { name: 'Masuk ke workspace' }).click();
  await expect(page.getByRole('heading', { name: 'Dashboard', exact: true })).toBeVisible();
  check('Login and session persist');
  await expect(page.locator('.stat-value').first()).toContainText('18');
  check('Dashboard renders seeded inventory');
  const points = await page.locator('.chart-wrap polyline').last().getAttribute('points');
  check('Chart displays nonzero real data', !points.split(' ').every(point => point.endsWith(',190')));
  await page.screenshot({ path: 'docs/screenshots/dashboard-desktop.png', fullPage: true });
  for (const [path, title] of [['/items', 'Data barang'], ['/items/create', 'Tambah barang'], ['/items/1', 'Detail barang'], ['/items/1/edit', 'Edit barang'], ['/categories', 'Kategori'], ['/movements', 'Riwayat transaksi'], ['/movements/create?type=in', 'Barang masuk'], ['/movements/create?type=out', 'Barang keluar']]) {
    response = await page.goto(base + path);
    check(`HTTP 200 ${path}`, response.status() === 200);
    await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
    check(`Desktop layout fits ${path}`, !overflow);
  }
  await page.goto(`${base}/items`);
  await page.screenshot({ path: 'docs/screenshots/inventory-desktop.png', fullPage: true });
  await page.getByRole('textbox', { name: 'Cari nama atau kode barang' }).fill('TidakAdaBarangIni');
  await page.getByRole('button', { name: 'Filter', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Barang tidak ditemukan' })).toBeVisible();
  check('Search empty state');
  await page.goto(`${base}/categories`);
  await page.getByRole('button', { name: 'Tambah kategori', exact: true }).first().click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button', { name: 'Tutup formulir' }).first().click();
  check('Category modal opens and closes');
  await page.getByRole('button', { name: 'Tambah kategori', exact: true }).first().click();
  await page.locator('#categoryCreateName').fill('Alat Tulis');
  await page.locator('#categoryCreateDescription').fill('Isian tetap tersimpan ketika validasi gagal.');
  await page.getByRole('dialog').getByRole('button', { name: 'Simpan kategori' }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('sudah digunakan');
  check('Duplicate category shows validation inside reopened modal');
  await expect(page.locator('#categoryCreateName')).toHaveValue('Alat Tulis');
  await expect(page.locator('#categoryCreateDescription')).toHaveValue('Isian tetap tersimpan ketika validasi gagal.');
  check('Category form preserves user input after validation failure');
  await page.getByRole('dialog').getByRole('button', { name: 'Tutup formulir' }).click();
  await page.goto(`${base}/movements/create?type=out&item=1`);
  const stock = Number(await page.locator('#item_id option:checked').getAttribute('data-stock'));
  await page.getByLabel('Jumlah barang').fill('5');
  await expect(page.locator('[data-preview-after]')).toContainText(String(stock - 5));
  check('Stock preview computes outgoing quantity');
  await page.getByLabel('Jumlah barang').fill(String(stock + 1));
  await expect(page.locator('[data-preview-error]')).toBeVisible();
  check('Client validation rejects insufficient stock');
  await page.getByLabel('Jumlah barang').fill('5');
  await page.screenshot({ path: 'docs/screenshots/stock-out-desktop.png', fullPage: true });
  const csrfResponse = await context.request.post(`${base}/movements`, { form: { type: 'out', item_id: 1, quantity: 1 }, maxRedirects: 0 });
  check('Missing CSRF token is rejected', csrfResponse.status() === 419);
  response = await context.request.get(`${base}/movements/export?type=out`);
  check('CSV download works', response.status() === 200 && (response.headers()['content-disposition'] || '').includes('.csv'));
  await page.goto(base);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('button', { name: 'Buka navigasi' })).toBeVisible();
  await page.getByRole('button', { name: 'Buka navigasi' }).click();
  await expect(page.locator('body')).toHaveClass(/sidebar-open/);
  await page.keyboard.press('Escape');
  await expect(page.locator('body')).not.toHaveClass(/sidebar-open/);
  check('Mobile navigation opens and closes');
  for (const path of ['/', '/items', '/categories', '/movements', '/movements/create?type=out', '/items/create']) {
    await page.goto(base + path);
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
    check(`Mobile layout fits ${path}`, !overflow);
  }
  await page.goto(base);
  await page.screenshot({ path: 'docs/screenshots/dashboard-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('.profile-button').click();
  await page.getByRole('button', { name: 'Keluar akun' }).click();
  await expect(page).toHaveURL(/\/login$/);
  check('Logout clears authenticated session');
  check('No browser JavaScript or HTTP 500 errors', issues.length === 0);
  await writeFile('docs/browser-results.json', JSON.stringify({ base, results, issues }, null, 2));
  console.log(JSON.stringify({ passed: results.length, issues, screenshots: 'docs/screenshots' }, null, 2));
} catch (error) {
  await writeFile('docs/browser-results.json', JSON.stringify({ results, issues, error: error.message }, null, 2));
  console.error(error.message);
  process.exitCode = 1;
} finally {
  await browser.close();
}